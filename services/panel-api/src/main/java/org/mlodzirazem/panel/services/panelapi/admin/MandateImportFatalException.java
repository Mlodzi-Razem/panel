package org.mlodzirazem.panel.services.panelapi.admin;

/**
 * A file-level failure (unreadable file, no header, missing columns) — nothing was imported.
 */
public class MandateImportFatalException extends RuntimeException {
    private final String code;

    public MandateImportFatalException(String code, String detail) {
        super(code + ": " + detail);
        this.code = code;
    }

    public String code() {
        return code;
    }
}
