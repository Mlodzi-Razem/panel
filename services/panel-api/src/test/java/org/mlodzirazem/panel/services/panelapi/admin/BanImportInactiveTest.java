package org.mlodzirazem.panel.services.panelapi.admin;

import org.junit.jupiter.api.Test;
import org.mlodzirazem.panel.services.panelapi.test.db.PostgresTest;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.context.ApplicationContext;

import static org.assertj.core.api.Assertions.assertThat;

@SpringBootTest
@PostgresTest
class BanImportInactiveTest {
    @Autowired
    ApplicationContext context;

    @Test
    void banImportBeansAreAbsentWithoutBanFile() {
        assertThat(context.getBeanNamesForType(BanImporter.class)).isEmpty();
        assertThat(context.getBeanNamesForType(BanImportRunner.class)).isEmpty();
        assertThat(context.getBeanNamesForType(BanImportProperties.class)).isEmpty();
    }
}
